"""Compatibility shim: expose ``frappe.parse_json`` inside Jinja templates.

Frappe v16 does not expose the whole ``frappe`` module to Jinja templates.
Instead ``frappe.utils.safe_exec.get_safe_globals()`` builds a restricted
``frappe`` namespace (``NamespaceDict``) that only contains an allow list of
helpers.

Print Designer exports embed the whole design (header / body / footer /
settings) as a JSON blob inside the exported template and parse it at render
time:

    {% set __pd_data = frappe.parse_json('...') %}

``parse_json`` is not part of the sandbox namespace, so rendering such a
template fails with::

    AttributeError: module has no attribute 'parse_json'

The template source is generated by the export flow, and the generated
templates are pasted into Print Format records, so rewriting them here would
mean modifying live Print Format HTML. Instead the sandbox namespace is
extended with the JSON helpers - ``json.loads`` is side effect free, so the
sandbox stays restricted to the same set of capabilities as before.

The patch is installed once per process and is idempotent.
"""

import frappe

_PATCH_FLAG = "_print_designer_jinja_namespace_patched"


def install_jinja_namespace_compat():
	"""Extend the Jinja sandbox namespace with ``frappe.parse_json``.

	Returns ``True`` when the shim is active.
	"""
	from frappe.utils import safe_exec

	if getattr(safe_exec, _PATCH_FLAG, False):
		return True

	original_get_safe_globals = safe_exec.get_safe_globals

	def get_safe_globals_with_parse_json():
		safe_globals = original_get_safe_globals()
		frappe_namespace = safe_globals.get("frappe")
		if frappe_namespace is not None and "parse_json" not in frappe_namespace:
			frappe_namespace["parse_json"] = frappe.parse_json
		return safe_globals

	safe_exec.get_safe_globals = get_safe_globals_with_parse_json
	setattr(safe_exec, _PATCH_FLAG, True)
	return True


def is_installed():
	from frappe.utils import safe_exec

	return bool(getattr(safe_exec, _PATCH_FLAG, False))
